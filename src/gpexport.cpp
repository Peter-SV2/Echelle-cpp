// The SAME ramp the app draws with, from palette.hpp. Two colour tables would
// mean an exported figure that is a different figure.
std::string series_hex(std::size_t i, std::size_t n) {
    const Rgb c = series_colour(i, n);
    char b[16];
    std::snprintf(b, sizeof b, "#%02x%02x%02x", c.r, c.g, c.b);
    return b;
}
constexpr const char* kInk = "#1a1a1a";
constexpr const char* kDim = "#6d6d6d";
constexpr const char* kLine = "#d7d7d7";

std::string esc(std::string_view s) {
    std::string o;
    o.reserve(s.size());
    for (char c : s) {
        if (c == '"' || c == '\\') o += '\\';
        o += c;
    }
    return o;
}

// Through write_atomic, like the session file. An export is a set of files
// that only mean anything together -- a .gp naming three .dat files, a CSV of
// the same numbers -- and a run that dies partway used to leave a new script
// pointing at last time's data, which reruns and draws the wrong figure
// without complaining.
bool write_text(const std::string& path, const std::string& body,
                std::string& err) {
    return write_atomic(path, body, err);
}

std::string fmt(double v) {
    char buf[40];
    std::snprintf(buf, sizeof buf, "%.10g", v);
    return buf;
}

std::string basename_of(const std::string& p) {
    const std::size_t s = p.find_last_of("/\\");
    return s == std::string::npos ? p : p.substr(s + 1);
}

const char* kind_style(Kind k) {
    switch (k) {
        case Kind::Line: return "with lines lw 2";
        case Kind::Hist:
        case Kind::Bars: return "with boxes";
        case Kind::Scatter: break;
    }
    return "with points pt 7 ps 1.2";
}

